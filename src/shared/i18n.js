const loadedLocales = new Map(Object.entries(BUILTIN));
let activeCode = "en";
let systemLangCache = null;

function mapBrowserLang(raw) {
  const s = String(raw || "en").toLowerCase();
  if (
    s.startsWith("zh-tw") ||
    s.startsWith("zh-hk") ||
    s.startsWith("zh-mo") ||
    s.includes("hant")
  )
    return "zh-TW";
  if (s.startsWith("zh")) return "zh-CN";
  const p = s.split("-")[0];
  const supported = [
    "id",
    "en",
    "ja",
    "ko",
    "es",
    "de",
    "nl",
    "fr",
    "ru",
    "ms",
    "fil",
    "th",
    "vi",
    "hi",
  ];
  if (p === "tl") return "fil";
  return supported.includes(p) ? p : "en";
}

async function detectOSLang() {
  if (systemLangCache) return systemLangCache;
  try {
    const invoke = window.__TAURI__?.core?.invoke;
    if (invoke) {
      systemLangCache = await invoke("get_system_language");
      return systemLangCache;
    }
  } catch {}
  systemLangCache = mapBrowserLang(navigator.language);
  return systemLangCache;
}

export async function setLanguage(pref = "auto") {
  const target = pref === "auto" ? await detectOSLang() : pref;
  if (!loadedLocales.has(target)) {
    try {
      const url = new URL(`./locales/${target}.json`, import.meta.url);
      const res = await fetch(url);
      if (res.ok) {
        const dict = await res.json();
        loadedLocales.set(target, dict);
      }
    } catch {
      // Fallback ke bahasa Inggris jika file locale belum tersedia
    }
  }
  activeCode = loadedLocales.has(target) ? target : "en";
  document.documentElement.lang = activeCode;
  return activeCode;
}

export function getActiveLang() {
  return activeCode;
}

export function getIntlLocale() {
  const map = {
    id: "id-ID",
    en: "en-US",
    ja: "ja-JP",
    ko: "ko-KR",
    es: "es-ES",
    de: "de-DE",
    nl: "nl-NL",
    fr: "fr-FR",
    ru: "ru-RU",
    "zh-CN": "zh-CN",
    "zh-TW": "zh-TW",
    ms: "ms-MY",
    fil: "fil-PH",
    th: "th-TH",
    vi: "vi-VN",
    hi: "hi-IN",
  };
  return map[activeCode] || "en-US";
}

export function t(key, vars = null) {
  const dict = loadedLocales.get(activeCode) || BUILTIN.en;
  const extra = EXTRA_STRINGS[activeCode] || EXTRA_STRINGS.en;
  let str =
    dict[key] ?? extra[key] ?? BUILTIN.en[key] ?? EXTRA_STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
